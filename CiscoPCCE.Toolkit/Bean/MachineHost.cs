using System.Xml.Serialization;
using System.Collections.Generic;

namespace CiscoPCCE.Toolkit.Bean
{

// Path("machineinventory")
[XmlRoot("machine")]
public class MachineHost : BaseApiBean {
  private List<MachineAddress>? addresses;
  private bool? autoGenerated;
  private string? baseUrlfromRefUrl;
  private int? changeStamp;
  private string? correlationId;
  private ReferenceBean department;
  private string? description;
  private string? hostName;
  private string? idFromRefUrl;
  private MachineType machineType;
  private MachineVersion machineVersion;
  private string? name;
  private ReferenceBean peripheralSet;
  private string? refURL;
  private ReferenceBean vmHostRef;
  private string? vmInstanceUuid;

  [XmlElement("networks")]
  [XmlElement("network")]
  public List<MachineAddress>? Addresses
  {
      get => addresses;
      set => addresses = value;
  }

  public bool? AutoGenerated
  {
      get => autoGenerated;
      set => autoGenerated = value;
  }

  public string? BaseUrlfromRefUrl
  {
      get => baseUrlfromRefUrl;
      set => baseUrlfromRefUrl = value;
  }

  public int? ChangeStamp
  {
      get => changeStamp;
      set => changeStamp = value;
  }

  public string? CorrelationId
  {
      get => correlationId;
      set => correlationId = value;
  }

  public ReferenceBean Department
  {
      get => department;
      set => department = value;
  }

  public string? Description
  {
      get => description;
      set => description = value;
  }

  public string? HostName
  {
      get => hostName;
      set => hostName = value;
  }

  public string? IdFromRefUrl
  {
      get => idFromRefUrl;
      set => idFromRefUrl = value;
  }

  [XmlElement("type")]
  public MachineType MachineType
  {
      get => machineType;
      set => machineType = value;
  }

  [XmlElement("versionInfo")]
  public MachineVersion MachineVersion
  {
      get => machineVersion;
      set => machineVersion = value;
  }

  public string? Name
  {
      get => name;
      set => name = value;
  }

  [XmlElement("peripheralSet")]
  public ReferenceBean PeripheralSet
  {
      get => peripheralSet;
      set => peripheralSet = value;
  }

  public string? RefURL
  {
      get => refURL;
      set => refURL = value;
  }

  [XmlElement("vmHost")]
  public ReferenceBean VmHostRef
  {
      get => vmHostRef;
      set => vmHostRef = value;
  }

  public string? VmInstanceUuid
  {
      get => vmInstanceUuid;
      set => vmInstanceUuid = value;
  }

  // Path("machineinventory")
  [XmlRoot("results")]
  public class MachineHostList : BaseApiListBean<MachineHost> {    public override List<MachineHost>? GetItems() => items;

    public override void SetItems(List<MachineHost>? value) => items = value;

  }
}

}