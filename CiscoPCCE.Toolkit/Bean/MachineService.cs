using System.Xml.Serialization;
using System.Collections.Generic;

namespace CiscoPCCE.Toolkit.Bean
{

// Path("machineinventory")
[XmlRoot("service")]
public class MachineService : BaseApiBean {
  private bool? autoGenerated;
  private List<MachineComponent>? components;
  private string? description;
  private string? enablePassword;
  private string? name;
  private string? pairing;
  private string? password;
  private int? port;
  private string? status;
  private ServiceType type;
  private string? uri;
  private string? userName;

  public bool? AutoGenerated
  {
      get => autoGenerated;
      set => autoGenerated = value;
  }

  [XmlElement("components")]
  [XmlElement("component")]
  public List<MachineComponent>? Components
  {
      get => components;
      set => components = value;
  }

  public string? Description
  {
      get => description;
      set => description = value;
  }

  public string? EnablePassword
  {
      get => enablePassword;
      set => enablePassword = value;
  }

  public string? Name
  {
      get => name;
      set => name = value;
  }

  public string? Pairing
  {
      get => pairing;
      set => pairing = value;
  }

  public string? Password
  {
      get => password;
      set => password = value;
  }

  public int? Port
  {
      get => port;
      set => port = value;
  }

  public string? Status
  {
      get => status;
      set => status = value;
  }

  public ServiceType Type
  {
      get => type;
      set => type = value;
  }

  public string? Uri
  {
      get => uri;
      set => uri = value;
  }

  public string? UserName
  {
      get => userName;
      set => userName = value;
  }

  // Path("machineinventory")
  [XmlRoot("results")]
  public class MachineServiceList : BaseApiListBean<MachineService> {    public override List<MachineService>? GetItems() => items;

    public override void SetItems(List<MachineService>? value) => items = value;

  }
}

}